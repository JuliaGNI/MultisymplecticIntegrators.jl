@testset "composite_quadrature(1, $k) matches the Gauss–Legendre table" for k in (64, 128)
    rule = MultisymplecticIntegrators.composite_quadrature(1, k)
    @test length(rule.nodes) == k
    @test length(rule.weights) == k
    @test all(abs.(rule.nodes .- TABLES[k].nodes) .<= 4eps())
    @test all(abs.(rule.weights .- TABLES[k].weights) .<= 4eps())
end

@testset "construct_quadrature_grid_with_boundary matches the 64- and 128-node tables" begin
    grid, _ = MultisymplecticIntegrators.construct_quadrature_grid_with_boundary([64, 128])
    interior = grid[:, 1:(64 * 128)]
    for (dim, k) in ((1, 64), (2, 128))
        nodes = sort(unique(interior[dim, :]))
        @test length(nodes) == k
        @test all(abs.(nodes .- TABLES[k].nodes) .<= 4eps())
    end
end
