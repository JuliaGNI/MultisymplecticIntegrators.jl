# Writes `test/helpers/weak_initial_condition_reference.jl`: the reference run of
# `WeakInitialCondition` on `Wave` that `test/couplings/weak_multipliers.jl` compares with.
#
# The first slab's bottom multiplier is the quadrature-weighted L² projection of the initial
# momentum, which the `WAVE_GALERKIN_DIRICHLET_BSPLINE` entry of `reference_values.jl` (the
# integrators at 294f023) does not use, so this coupling has a reference of its own. The run is
# the one of the test's `wave_run(Float64)`: five steps of `h = 0.05` on `Wave` at its default
# parameters, a degree-2 tensor B-spline ansatz on `(2, 20)` cells with three Gauss nodes per cell
# and `x_boundary = Dirichlet()`, and the `Continuation()` guess.
#
# Run it from the repository root, on a tree whose `src/` is committed:
#
#     julia --startup-file=no --project=. --check-bounds=yes scripts/weak_initial_condition_reference.jl

using MultisymplecticIntegrators
using SimpleSplines: Dirichlet
using LinearAlgebra: BLAS
import Pkg

const ROOT = dirname(@__DIR__)
const OUTPUT = joinpath(ROOT, "test", "helpers", "weak_initial_condition_reference.jl")

const CONSTRUCTOR = "SpaceTimeGalerkin(TensorBSplineAnsatz(degree = 2, ncells = (2, 20), " *
                    "xspan = (0.0, 1.0), n = 3, x_boundary = Dirichlet()), WeakInitialCondition())"
const PROBLEM = "Wave.problem(T = Float64, timespan = (0.0, 0.25), timestep = 0.05, xstep = 0.05)"

function source_commit()
    dirty = readchomp(`git -C $ROOT status --porcelain -- src`)
    isempty(dirty) ||
        error("src/ has uncommitted changes; commit them first:\n$dirty")
    return readchomp(`git -C $ROOT rev-parse HEAD`)
end

function check_bounds_flag()
    flag = Base.JLOptions().check_bounds
    return flag == 1 ? "yes" : flag == 2 ? "no" : "auto"
end

matrix(rows) = permutedims(reduce(hcat, rows))

function main()
    commit = source_commit()
    BLAS.set_num_threads(1)
    problem = Wave.problem(
        T = Float64, timespan = (0.0, 0.25), timestep = 0.05, xstep = 0.05)
    ansatz = TensorBSplineAnsatz(degree = 2, ncells = (2, 20), xspan = (0.0, 1.0), n = 3,
        x_boundary = Dirichlet())
    result = integrate(problem, SpaceTimeGalerkin(ansatz, WeakInitialCondition());
        on_failure = :error)
    steps = length(result.traces)
    steps == 5 || error("expected 5 steps, got $steps")
    sol, stats = result.solution, result.stats
    entry = (constructor = CONSTRUCTOR, problem = PROBLEM, seed = nothing, status = :ok,
        steps = steps,
        u = matrix(sol.u[n] for n in 1:steps),
        v = matrix(sol.v[n] for n in 1:steps),
        w = matrix(sol.w[n] for n in 1:steps),
        iterations = stats.iterations, converged = stats.converged,
        residual = stats.residuals)
    deps = sort!([(info.name, info.version)
                  for info in values(Pkg.dependencies()) if info.is_direct_dep])
    open(OUTPUT, "w") do io
        println(io, "# The reference run of `WeakInitialCondition` at commit ",
            commit[1:7], ". Generated by")
        println(io, "# `scripts/weak_initial_condition_reference.jl`; do not edit by hand.")
        println(io, "#")
        println(io, "# commit: ", commit)
        println(io, "# Julia: ", VERSION, ", --check-bounds=", check_bounds_flag(), ", ",
            Threads.nthreads(), " thread(s), ", BLAS.get_num_threads(), " BLAS thread(s)")
        for (name, version) in deps
            println(io, "# ", name, " ", version)
        end
        println(io, "#")
        println(io, "# `u`, `v`, `w` hold one row per step, on the nodes of the problem's output")
        println(io, "# grid. `iterations`, `converged` and `residual` (absolute) are the Newton")
        println(io, "# record of each step, as `integrate` returns it in `stats`. The entry has no")
        println(io, "# `energy_error`, which the test does not read.")
        println(io)
        println(io, "const WAVE_WEAK_INITIAL_CONDITION = ", repr(entry))
    end
    return OUTPUT
end

main()
